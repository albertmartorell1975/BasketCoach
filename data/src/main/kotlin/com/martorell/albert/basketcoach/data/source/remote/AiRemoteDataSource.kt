package com.martorell.albert.basketcoach.data.source.remote

import com.martorell.albert.basketcoach.data.network.dto.AiAnalysisResponseDto
import com.martorell.albert.basketcoach.data.network.dto.ChatMessageDto

/**
 * Remote data source abstraction for communicating with OpenAI-compatible AI inference endpoints
 * (such as DevExpert Inference or Google Gemini).
 *
 * Implementations throw technical framework exceptions (e.g. [java.io.IOException], [com.martorell.albert.basketcoach.data.mapper.HttpException])
 * directly, allowing repositories to map them into domain errors via safe execution.
 */
interface AiRemoteDataSource {
    /**
     * Executes batch tactical analysis request and returns the parsed DTO.
     *
     * @param gameContext Textual summary of Phase 1 matches and statistics.
     * @return [AiAnalysisResponseDto] containing insights and drills.
     */
    suspend fun generateAnalysis(gameContext: String): AiAnalysisResponseDto

    /**
     * Dispatches a single chat completion query with thread history and optional grounding context.
     *
     * @param conversationHistory Prior messages in the chat thread.
     * @param newPrompt The new query submitted by the coach.
     * @param gameContext Optional grounding context summarizing matches.
     * @return Raw text response generated by the AI model.
     */
    suspend fun generateChatResponse(
        conversationHistory: List<ChatMessageDto>,
        newPrompt: String,
        gameContext: String? = null
    ): String
}
