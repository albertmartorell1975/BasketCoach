package com.martorell.albert.basketcoach.data.source.remote

import com.martorell.albert.basketcoach.data.network.dto.ChatMessageDto
import com.martorell.albert.basketcoach.data.network.dto.JevDecisionRequestDto
import com.martorell.albert.basketcoach.data.network.dto.JevDecisionResponseDto

/**
 * Remote data source abstraction for communicating with OpenAI-compatible AI inference endpoints
 * (such as DevExpert Inference or Google Gemini).
 *
 * Provides purely mechanical network transport: dispatches requests, handles network timeouts and failover,
 * and returns raw response content or decision response DTOs.
 *
 * Implementations throw technical framework exceptions (e.g. [java.io.IOException], [com.martorell.albert.basketcoach.data.mapper.HttpException])
 * directly, allowing repositories to map them into domain errors via safe execution.
 */
interface AiRemoteDataSource {

    /**
     * Dispatches a chat completion request with the provided [messages] and [temperature],
     * transparently managing provider failover and returning the raw string response from the model.
     *
     * @param messages List of conversation messages (system, user, assistant).
     * @param temperature Sampling temperature regulating generation randomness.
     * @return Raw text response generated by the AI model.
     */
    suspend fun executeChatCompletion(
        messages: List<ChatMessageDto>,
        temperature: Double
    ): String

    /**
     * Dispatches a raw decisions API request to the DevExpert endpoint (`POST /decisions`),
     * returning the unparsed decision response DTO.
     *
     * @param request DTO containing the model, state mapping, and question definitions.
     * @return Parsed [JevDecisionResponseDto] returned from the endpoint.
     */
    suspend fun executeDecision(
        request: JevDecisionRequestDto
    ): JevDecisionResponseDto

    /**
     * Returns true if the currently active inference configuration targets DevExpert.
     */
    fun isUsingDevExpert(): Boolean
}
