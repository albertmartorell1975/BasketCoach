package com.martorell.albert.basketcoach.domain.repository

import com.martorell.albert.basketcoach.domain.model.ChatMessage
import com.martorell.albert.basketcoach.domain.model.DomainError
import com.martorell.albert.basketcoach.domain.model.Result

/**
 * Domain repository contract managing the single-thread coaching AI chat conversation.
 */
interface ChatRepository {
    /**
     * Retrieves all chat messages in chronological order.
     *
     * @return [Result.Success] containing the list of [ChatMessage] entities, or [Result.Error] with [DomainError].
     */
    suspend fun getMessages(): Result<List<ChatMessage>, DomainError>

    /**
     * Sends a coach's query or prompt to the AI coaching assistant and returns the AI response.
     *
     * @param messageText Text prompt or inquiry sent by the coach.
     * @return [Result.Success] with the resulting [ChatMessage] generated by the AI assistant,
     * or [Result.Error] with [DomainError] if transmission or generation fails.
     */
    suspend fun sendMessage(messageText: String): Result<ChatMessage, DomainError>
}
