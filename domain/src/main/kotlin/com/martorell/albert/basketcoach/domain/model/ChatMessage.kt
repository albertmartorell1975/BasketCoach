package com.martorell.albert.basketcoach.domain.model

/**
 * An individual message exchanged within the single-thread coaching AI chat.
 *
 * @property id Unique identifier for the message.
 * @property sender The message author ([MessageSender.COACH] or [MessageSender.AI]).
 * @property text Raw content of the message.
 * @property timestamp Epoch millisecond timestamp when the message was recorded.
 */
data class ChatMessage(
    val id: String,
    val sender: MessageSender,
    val text: String,
    val timestamp: Long
) {
    /**
     * True if the message was sent by the coach.
     */
    val isFromCoach: Boolean
        get() = sender == MessageSender.COACH

    /**
     * True if the message was generated by the AI assistant.
     */
    val isFromAi: Boolean
        get() = sender == MessageSender.AI
}
